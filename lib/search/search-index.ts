/**
 * Normalizes filter strings so queries from modals and pages match consistently.
 */
export function normalizeCategoryFilter(filter?: string): string {
  if (!filter) return "all";
  const f = filter.toLowerCase().trim();
  if (f === "all") return "all";
  if (f.includes("vertical") || f === "verticals") return "verticals";
  if (f.includes("product") || f.includes("frame") || f === "products") return "products";
  if (f.includes("material") || f.includes("spec") || f.includes("machin") || f === "materials") return "materials";
  if (f.includes("action") || f.includes("portal") || f.includes("tool") || f === "actions" || f === "portals") return "actions";
  return "all";
}

/**
 * Search the comprehensive Frames Cottage Studio archive.
 * Performs fuzzy, case-insensitive keyword and term matching.
 */
export function searchStudio(
  query: string = "",
  categoryFilter: string = "all"
): SearchGroupedResults {
  const cleanQuery = query.trim().toLowerCase();
  const normalizedCategory = normalizeCategoryFilter(categoryFilter);

  // Filter by category first if specified
  let filtered = STUDIO_SEARCH_INDEX;
  if (normalizedCategory !== "all") {
    filtered = filtered.filter((item) => item.category === normalizedCategory);
  }

  // If no query string, return all items matching the category filter
  if (!cleanQuery) {
    const verticals = filtered.filter((i) => i.category === "verticals");
    const products = filtered.filter((i) => i.category === "products");
    const materials = filtered.filter((i) => i.category === "materials");
    const actions = filtered.filter((i) => i.category === "actions");

    return {
      verticals,
      products,
      materials,
      actions,
      all: filtered,
      totalCount: filtered.length,
    };
  }

  // Split query into individual search tokens
  const tokens = cleanQuery.split(/\s+/).filter(Boolean);

  const matched = filtered.filter((item) => {
    // Searchable corpus for the item
    const corpus = [
      item.title,
      item.subtitle,
      item.categoryLabel,
      item.description,
      item.priceOrLeadTime,
      item.badge || "",
      ...item.specs,
      ...item.keywords,
    ]
      .join(" ")
      .toLowerCase();

    // Every token must match somewhere in the item's corpus
    return tokens.every((token) => corpus.includes(token));
  });

  // Sort matched results: direct title matches first
  matched.sort((a, b) => {
    const aTitleMatch = a.title.toLowerCase().includes(cleanQuery);
    const bTitleMatch = b.title.toLowerCase().includes(cleanQuery);
    if (aTitleMatch && !bTitleMatch) return -1;
    if (!aTitleMatch && bTitleMatch) return 1;
    return 0;
  });

  const verticals = matched.filter((i) => i.category === "verticals");
  const products = matched.filter((i) => i.category === "products");
  const materials = matched.filter((i) => i.category === "materials");
  const actions = matched.filter((i) => i.category === "actions");

  return {
    verticals,
    products,
    materials,
    actions,
    all: matched,
    totalCount: matched.length,
  };
}
